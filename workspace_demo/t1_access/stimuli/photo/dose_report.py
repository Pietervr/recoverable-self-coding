"""Delivered-SNR report on the eight Stage A DEV-CAL primary views at all seven strengths - pixels only, no model.

T, the exact input pipeline a stimulus passes through before the model: clip -> round-half-even 8-bit -> lossless
PNG -> PNG decode (Pillow) -> the NATIVE image processor of the instrumented path. That processor is mlx-vlm 0.6.3's
torch-free `Qwen3VLImageProcessor` (a numpy port of HF's qwen2/3-VL processor; mlx-vlm uses it for `qwen3_5`),
configured from the frozen snapshot's preprocessor_config.json (patch 16, temporal 2, merge 2, mean = std = 0.5).
Following §8.3, with the same a in numerator and denominator:
    s_del = T(mu + aS) - T(mu)          e_del = T(mu + aS + sqrt(1 - a^2) N) - T(mu + aS)
    delivered dB = 10 log10(||s_del||^2 / ||e_del||^2), endpoints recorded as zero numerator / denominator.
After clipping and quantisation this is a reference-based effective corruption ratio, not recovered additive SNR.

Masks for this report: one per (view, non-clean level), drawn under an OPAQUE nonce - a seeded permutation of the
report's slot list, so a slot's noise does not depend on the concept, its pixels or its label. Stage A's own schedule
is generated by the same mechanism at run time. The noise-only input is built by dose.zero(), which never opens a
photograph.

    .venv-image/bin/python stimuli/photo/dose_report.py
"""

from __future__ import annotations

import hashlib
import io
import json
import math
import random
from pathlib import Path

import numpy as np
from PIL import Image

import dose

HERE = Path(__file__).resolve().parent
IMAGES = Path.home() / "things-plus/cc0/object_images_CC0"
SNAPSHOT = Path.home() / (".cache/huggingface/hub/models--mlx-community--Qwen3.6-27B-4bit/snapshots/"
                          "c000ac2c2057d94be3fa931000c31723aac53282")
REPORT_SEED = 20261005


def processor():
    """mlx-vlm's torch-free Qwen3VL image processor, configured from the frozen snapshot's preprocessor_config.json
    exactly as HF maps it: size.shortest_edge -> min_pixels, size.longest_edge -> max_pixels."""
    from mlx_vlm.models.qwen3_vl.processing_qwen3_vl import Qwen3VLImageProcessor
    cfg = json.loads((SNAPSHOT / "preprocessor_config.json").read_text())
    return Qwen3VLImageProcessor(patch_size=cfg["patch_size"], temporal_patch_size=cfg["temporal_patch_size"],
                                 merge_size=cfg["merge_size"], min_pixels=cfg["size"]["shortest_edge"],
                                 max_pixels=cfg["size"]["longest_edge"], image_mean=cfg["image_mean"],
                                 image_std=cfg["image_std"])


def T(rgb8: np.ndarray, proc) -> tuple[np.ndarray, dict]:
    png = dose.to_png(rgb8)
    dec = np.asarray(Image.open(io.BytesIO(png)).convert("RGB"))
    assert np.array_equal(dec, rgb8), "PNG round trip is not lossless"
    out = proc(images=[Image.fromarray(dec)], return_tensors="np")
    pv = np.asarray(out["pixel_values"], dtype=np.float64)
    grid = np.asarray(out["image_grid_thw"]).tolist()
    return pv, {"png_sha256": hashlib.sha256(png).hexdigest(),
                "tensor_sha256": hashlib.sha256(np.asarray(out["pixel_values"], dtype=np.float32).tobytes()).hexdigest(),
                "grid_thw": grid, "merged_tokens": int(np.prod(grid[0])) // 4}


def main() -> int:
    pool = json.loads((HERE / "dev_pool.json").read_text())
    views = [r for r in pool["roles"] if r["stage_a_primary_view"]]
    grid = dose.a_grid()
    proc = processor()
    levels = list(grid["a"].items())
    slots = [(v["concept"], name) for v in views for name, a in levels if name != "clean"]
    perm = list(range(len(slots)))
    random.Random(REPORT_SEED).shuffle(perm)
    nonce = {slot: f"report-mask-{perm[i]}" for i, slot in enumerate(slots)}

    mu8, _ = dose.quantise(np.full((dose.CANVAS, dose.CANVAS), dose.MU))
    T_mu, _ = T(mu8, proc)
    rows, defects = [], []
    for v in views:
        canvas, geom = dose.load_canvas(IMAGES / v["thingsplus_image"])
        g = dose.luma(canvas)
        S = dose.signal(g)
        per = []
        for name, a in levels:
            if name == "noise_only":
                N = dose.noise(nonce[(v["concept"], name)])
                I = dose.zero(nonce[(v["concept"], name)])
                ref = np.full_like(I, dose.MU)
            else:
                N = dose.noise(nonce[(v["concept"], name)]) if name != "clean" else np.zeros_like(S)
                I = dose.mix(S, N, a)
                ref = dose.MU + a * S
            q, clip = dose.quantise(I)
            qref, _ = dose.quantise(ref)
            T_i, ident = T(q, proc)
            T_ref, _ = T(qref, proc)
            s_del, e_del = T_ref - T_mu, T_i - T_ref
            num, den = float((s_del ** 2).sum()), float((e_del ** 2).sum())
            delivered = (10 * math.log10(num / den) if num > 0 and den > 0 else None)
            nominal = (10 * math.log10(a * a / (1 - a * a)) if 0 < a < 1 else None)
            per.append({"level": name, "a": a, "k": 8 * a, "nominal_db": nominal, "delivered_db": delivered,
                        "s_del_sq": num, "e_del_sq": den, **clip,
                        **dose.stats(I, S if name != "noise_only" else None, N if name not in ("clean",) else None),
                        "post_quant_mean": float(q[..., 0].mean() / 255), "post_quant_rms": float(q[..., 0].std() / 255),
                        **ident})
        finite = [p["delivered_db"] for p in per if p["delivered_db"] is not None]
        if finite != sorted(finite):
            defects.append(f"{v['concept']}: delivered dB not increasing with a: {[round(x, 2) for x in finite]}")
        worst = max(p["clipped_fraction"] for p in per)
        if worst > 0.01:
            defects.append(f"{v['concept']}: clipped fraction up to {worst:.4f}")
        rows.append({"concept": v["concept"], "family": v["family"], "image": v["thingsplus_image"],
                     "geometry": geom, "levels": per})

    out = {"a_grid": grid, "mu": dose.MU, "r": dose.R, "noise_seed": dose.NOISE_SEED, "report_seed": REPORT_SEED,
           "processor": {"class": type(proc).__name__, "mlx_vlm": __import__("mlx_vlm").__version__,
                         "file_sha256": hashlib.sha256(Path(__import__("mlx_vlm.models.qwen3_vl.processing_qwen3_vl",
                                                                      fromlist=["x"]).__file__).read_bytes()).hexdigest()},
           "dose_py_sha256": hashlib.sha256((HERE / "dose.py").read_bytes()).hexdigest(),
           "script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
           "T_mu_tensor_sha256": hashlib.sha256(T_mu.astype(np.float32).tobytes()).hexdigest(),
           "views": rows, "defects": defects}
    (HERE / "dose_report.json").write_text(json.dumps(out, indent=1) + "\n")
    print(f"a grid sha256 {grid['sha256'][:16]}...  processor {out['processor']['class']}")
    for r in rows:
        def cell(p):
            db = "-" if p["delivered_db"] is None else f"{p['delivered_db']:+.1f}"
            return f"{p['level']}:{db}/clip{p['clipped_fraction']:.3f}"
        cells = "  ".join(cell(p) for p in r["levels"])
        print(f"{r['concept']:<10} {r['geometry']['fitted_size']} tokens {r['levels'][0]['merged_tokens']}  {cells}")
    print("defects:", defects or "none")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
