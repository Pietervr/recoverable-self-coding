"""Row 19: the producer-runtime identity oracle (Codex's bounded design opinion, RSC 9d8f706, 3 October 2026).

WHY. `analyze.dataset_identity` hashes the dataset's bytes. Rep 2's response array differs between the Mac and Lengau at
the last bit (98 of 10,752 values, 1-8 ULPs; chpc/results/row19_rep2_generation_diff/), so the Mac-side watch and
comparator, which rebuild each rep's dataset to recompute its identity, cannot reproduce rep 2's identity although
Lengau's own rebuild reproduces it exactly. The oracle lets the verification tools establish the EXACT identity equality
through an independent recomputation under the admitted pinned producer runtime, and nothing else.

WHAT IT IS. `<root>/identity_oracle.json`, written ON THE PRODUCER (Lengau, under the pinned wrapper) by `generate`:
for every task binding in the root it (1) checks that the effective numerical snapshot of THIS process (the actually
loaded canonical sources' digests, the runtime labels, the model globals) equals the binding's snapshot and the
manifest's pins and environment; (2) rebuilds the dataset, the outer folds and the full B resample-index matrix from
the manifest and the resolved seed; (3) recomputes the identity with that effective snapshot and records whether it
equals the binding's; (4) records canonical digests of the non-response data and metadata (k, concept, family, layers,
group, generator metadata), of the actual outer folds and of the full draw matrix, plus the response bytes' digest as a
diagnostic; (5) binds the entry to the exact manifest bytes and to a canonical digest of the immutable task binding.
It is pulled with the root as part of the same fresh snapshot the watch uses; an unchanged binding needs no new oracle.

WHAT A CONSUMER MAY DO WITH IT (`verify_entry`). Only when its own local rebuild gives a DIFFERENT identity: accept the
binding's identity as the frozen task's when the oracle's entry (a) is bound to this manifest's exact bytes and to this
binding's canonical digest, (b) names this rep, resolved seed and B, (c) was generated by a process whose effective
snapshot equals the binding's and whose sources and runtime equal the pins and the pinned environment, (d) records an
independently recomputed identity equal to the binding's, and (e) whose structural digests - everything in the identity
except the response bytes, plus the actual folds and the full draw matrix - equal the consumer's own local
reconstruction. Anything else refuses, exactly as before: an absent oracle leaves today's behaviour; an invalid, stale,
ambiguous or mismatched entry cannot supply the fallback. No tolerance, rounding or relabelling anywhere; the records
are still validated against the identity they carry and against the locally rebuilt draws (which the digest check has
shown equal to the producer's). The verification basis per rep ("local" or "oracle") is reported, never silent.

CLI (on the producer, from workspace_demo/t1_access):
    t1py chpc/row19_identity_oracle.py --manifest chpc/row19_slice_manifest.json --root <root>     # writes <root>/identity_oracle.json
"""
import argparse, hashlib, json, os, platform, socket, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
T1 = os.path.abspath(os.path.join(HERE, ".."))
if T1 not in sys.path:
    sys.path.insert(0, T1)

VERSION = 1
ORACLE_NAME = "identity_oracle.json"
BINDING_KEYS = ("manifest_sha", "rep", "ds_seed", "ident", "code_hash", "policy", "n_rep", "until", "ckpt", "orig", "numerical")
CANONICAL_SOURCES = ("analyze.py", "models.py", "simulate.py")
STRUCTURAL = ("k", "concept", "family", "layers", "group", "meta", "folds", "draws")
CANON = ("arrays: numpy float64 C-order bytes prefixed by repr(shape) (as dataset_identity); group and draws: int64 C-order bytes "
         "prefixed by repr(shape); meta and folds: json.dumps(sort_keys=True, default=str) of the generator metadata dict and of "
         "the folds as lists of ints; every digest sha256 hex")


def sha_bytes(b):
    return hashlib.sha256(b).hexdigest()


def sha_file(p):
    with open(p, "rb") as fh:
        return sha_bytes(fh.read())


def canonical_binding_digest(binding):
    """A digest of the immutable task binding: exactly BINDING_KEYS (the runner's binding dict), never the task document's
    evolving watermark or run history. A binding missing any key, or carrying any other key, has no digest."""
    if not isinstance(binding, dict) or sorted(binding) != sorted(BINDING_KEYS):
        raise ValueError(f"the task binding does not carry exactly {BINDING_KEYS}")
    return sha_bytes(json.dumps({k: binding[k] for k in BINDING_KEYS}, sort_keys=True, default=str).encode())


def _arr_digest(a, dtype):
    import numpy as np
    a = np.ascontiguousarray(np.asarray(a, dtype=dtype))
    return sha_bytes(repr(a.shape).encode() + a.tobytes()), list(a.shape)


def structural_digests(ds, folds, draws):
    """Canonical digests of everything the identity hashes except the response bytes, plus the actual folds and the full
    draw matrix; the response digest is included as a diagnostic only (`y`)."""
    import numpy as np
    out, shapes = {}, {}
    for name in ("k", "concept", "family", "layers"):
        out[name], shapes[name] = _arr_digest(getattr(ds, name), np.float64)
    out["y"], shapes["y"] = _arr_digest(ds.y, np.float64)
    if ds.group is None:
        out["group"], shapes["group"] = None, None
    else:
        out["group"], shapes["group"] = _arr_digest(ds.group, np.int64)
    meta = {k: ds.meta.get(k) for k in ("generator", "theta", "D", "rho", "seed")}
    out["meta"] = sha_bytes(json.dumps(meta, sort_keys=True, default=str).encode())
    out["folds"] = sha_bytes(json.dumps([[int(c) for c in f] for f in folds], sort_keys=True).encode())
    shapes["folds"] = [int(len(f)) for f in folds]
    out["draws"], shapes["draws"] = _arr_digest(draws, np.int64)
    return out, shapes


def rebuild(manifest, rep, seed):
    """The frozen task's dataset, folds, B and full draw matrix from the manifest and the resolved seed (no fit)."""
    import numpy as np
    import analyze as A, simulate as S
    st, c = manifest["setting"], manifest["cfg"]
    cfg = A.Config(start_policy=c["start_policy"], interval=c["interval"], n_boot_refit=int(c["n_boot_refit"]),
                   n_starts=int(c["n_starts"]), n_starts_inner=int(c["n_starts_inner"]), refit_min_usable=float(c["refit_min_usable"]),
                   n_outer=int(c["n_outer"]), n_inner=int(c["n_inner"]))
    kw = dict(st["grid"]); theta = S.generator_theta(st["generator"], **kw)
    if S.dataset_seed(st["generator"], kw, int(rep), int(st["D"]), int(manifest["datasets"]["seed_base"])) != int(seed):
        raise ValueError("the resolved seed is not the manifest's for this rep")
    ds = S.make_dataset(st["generator"], theta, n_per_family=int(st["n_per_family"]), D=int(st["D"]), layers=np.array(st["layers"]),
                        rho=float(st["rho"]), seed=int(seed))
    ds.meta.update(generator=st["generator"], theta=[float(x) for x in theta], D=int(st["D"]), rho=float(st["rho"]), seed=int(seed))
    folds = A.stratified_folds(ds.family, cfg.n_outer, int(seed))
    n_rep = int(cfg.n_boot_refit)
    draws = A.stratified_resample(ds.family, n_rep, np.random.default_rng(int(seed)))
    return cfg, ds, folds, n_rep, draws


def effective_snapshot():
    import analyze as A
    return json.loads(json.dumps(A.numerical_snapshot(), default=str))


def snapshot_problems(snap, manifest):
    """The snapshot's sources against the manifest's pins and its runtime labels against the pinned environment."""
    problems = []
    if not isinstance(snap, dict):
        return ["snapshot is not a dict"]
    files = snap.get("files"); rt = snap.get("runtime", {})
    if not isinstance(files, dict) or sorted(files) != sorted(CANONICAL_SOURCES):
        problems.append(f"snapshot does not name exactly the canonical sources {CANONICAL_SOURCES}")
    else:
        pins = manifest["code"]["files"]
        for name in CANONICAL_SOURCES:
            pin = pins.get(name)
            if not (isinstance(pin, str) and len(pin) == 64) or str(files[name]) != pin[:16]:
                problems.append(f"snapshot source {name} {files.get(name)!r} is not the manifest's pin")
    want = manifest["environment"]
    for k in ("python", "jax", "numpy", "scipy"):
        if str(rt.get(k)) != str(want.get(k)):
            problems.append(f"snapshot runtime {k} {rt.get(k)!r} is not the pinned {want.get(k)!r}")
    return problems


def generate(manifest_path, root, tool_path=None):
    """Write <root>/identity_oracle.json for every task binding in the root; returns the document. Entries that cannot be
    established (a snapshot that is not this process's, a seed that is not the manifest's, an identity this process does
    not reproduce) are written with `usable: false` and their problems, so a consumer refuses them explicitly."""
    import analyze as A
    with open(manifest_path, "rb") as fh:
        mbytes = fh.read()
    manifest = json.loads(mbytes.decode("utf-8")); msha = sha_bytes(mbytes)
    snap = effective_snapshot()
    tool = tool_path or os.path.abspath(__file__)
    doc = {"version": VERSION, "manifest_sha256": msha, "root": os.path.basename(os.path.abspath(root).rstrip("/")),
           "canonicalization": CANON,
           "generated": {"time": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "host": socket.gethostname(),
                         "platform": platform.platform(), "machine": platform.machine(), "python_executable": sys.executable,
                         "runtime": snap.get("runtime"), "sources": snap.get("files"), "snapshot": snap,
                         "tool": os.path.basename(tool), "tool_sha256": sha_file(tool),
                         "snapshot_problems": snapshot_problems(snap, manifest)},
           "entries": {}}
    import re
    for name in sorted(os.listdir(root)):
        if not re.fullmatch(r"task_\d+\.json", name):          # the task bindings only, never task_index.json
            continue
        task = json.load(open(os.path.join(root, name)))
        b = task.get("binding") if isinstance(task, dict) else None
        problems = []
        try:
            bd = canonical_binding_digest(b)
        except ValueError as e:
            doc["entries"][name] = {"usable": False, "problems": [str(e)]}; continue
        rep, seed, n_rep = int(b["rep"]), int(b["ds_seed"]), int(b["n_rep"])
        if b["manifest_sha"] != msha:
            problems.append("the binding's manifest sha is not this manifest's bytes")
        if b["numerical"] != snap:
            problems.append("the binding's numerical snapshot is not this process's effective snapshot")
        problems += doc["generated"]["snapshot_problems"]
        entry = {"rep": rep, "ds_seed": seed, "n_rep": n_rep, "binding_digest": bd, "binding_ident": b["ident"]}
        try:
            cfg, ds, folds, n_rep_m, draws = rebuild(manifest, rep, seed)
            if n_rep_m != n_rep:
                problems.append(f"the manifest's B {n_rep_m} is not the binding's {n_rep}")
            ident = A.dataset_identity(ds, cfg, seed, n_rep, folds, numerical=snap)
            digests, shapes = structural_digests(ds, folds, draws)
            entry.update(identity=ident, identity_equals_binding=(ident == b["ident"]), digests=digests, shapes=shapes)
            if ident != b["ident"]:
                problems.append("this process does not reproduce the binding's identity")
        except Exception as e:
            problems.append(f"rebuild failed: {type(e).__name__}: {e}")
        entry["problems"] = problems; entry["usable"] = not problems
        doc["entries"][str(rep)] = entry
    out = os.path.join(root, ORACLE_NAME); tmp = out + ".tmp"
    with open(tmp, "w") as fh:
        json.dump(doc, fh, indent=1, sort_keys=True); fh.write("\n"); fh.flush(); os.fsync(fh.fileno())
    os.replace(tmp, out)
    return doc


def load(root_or_path):
    p = root_or_path if root_or_path.endswith(".json") else os.path.join(root_or_path, ORACLE_NAME)
    if not os.path.exists(p):
        return None
    try:
        doc = json.load(open(p))
    except Exception as e:
        return {"__invalid__": f"not JSON: {e}"}
    doc["__path__"] = p; doc["__sha256__"] = sha_file(p)
    return doc


def verify_entry(oracle, manifest_path, binding, local_digests):
    """May this oracle establish the binding's identity for this rep? (True, description) or (False, [problems]).
    `local_digests` are the consumer's own structural digests of its local reconstruction (structural_digests)."""
    problems = []
    if not isinstance(oracle, dict) or "__invalid__" in oracle:
        return False, [f"oracle unreadable: {oracle.get('__invalid__') if isinstance(oracle, dict) else 'not a document'}"]
    if oracle.get("version") != VERSION or not isinstance(oracle.get("entries"), dict) or not isinstance(oracle.get("generated"), dict):
        return False, ["oracle structure is not version 1 (version, generated, entries)"]
    with open(manifest_path, "rb") as fh:
        msha = sha_bytes(fh.read())
    manifest = json.load(open(manifest_path))
    if oracle.get("manifest_sha256") != msha:
        problems.append("oracle is bound to other manifest bytes")
    try:
        bd = canonical_binding_digest(binding)
    except ValueError as e:
        return False, [str(e)]
    if binding["manifest_sha"] != msha:
        problems.append("the binding's manifest sha is not this manifest's bytes")
    rep, seed, n_rep = int(binding["rep"]), int(binding["ds_seed"]), int(binding["n_rep"])
    entries = [e for k, e in oracle["entries"].items() if isinstance(e, dict) and e.get("rep") == rep]
    if len(entries) != 1:
        problems.append(f"oracle holds {len(entries)} entries for rep {rep} (exactly one required)")
        return False, problems
    e = entries[0]
    for k, v in (("ds_seed", seed), ("n_rep", n_rep), ("binding_digest", bd)):
        if e.get(k) != v:
            problems.append(f"oracle entry {k} {str(e.get(k))[:20]!r} is not this binding's {str(v)[:20]!r}")
    gen = oracle["generated"]
    if gen.get("snapshot") != binding.get("numerical"):
        problems.append("the oracle's generating snapshot is not the binding's snapshot")
    problems += [f"oracle generator: {p}" for p in snapshot_problems(gen.get("snapshot"), manifest)]
    if gen.get("sources") != (gen.get("snapshot") or {}).get("files") or gen.get("runtime") != (gen.get("snapshot") or {}).get("runtime"):
        problems.append("the oracle's declared sources/runtime do not equal its snapshot's")
    if e.get("usable") is not True or e.get("identity_equals_binding") is not True or e.get("problems"):
        problems.append(f"oracle entry is not usable: {e.get('problems')}")
    if e.get("identity") != binding.get("ident") or e.get("binding_ident") != binding.get("ident"):
        problems.append("the oracle's recomputed identity is not the binding's")
    d = e.get("digests")
    if not isinstance(d, dict) or any(k not in d for k in STRUCTURAL):
        problems.append("oracle entry lacks the structural digests")
    else:
        for k in STRUCTURAL:
            if d.get(k) != local_digests.get(k):
                problems.append(f"structural digest {k} differs from the local reconstruction")
    if problems:
        return False, problems
    return True, (f"pinned-runtime oracle generated {gen.get('time')} on {gen.get('host')} ({gen.get('machine')}, "
                  f"python {str(gen.get('runtime', {}).get('python'))}, numpy {str(gen.get('runtime', {}).get('numpy'))}); "
                  f"response-byte digest producer {str(d.get('y'))[:12]} vs local {str(local_digests.get('y'))[:12]}")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True); ap.add_argument("--root", required=True)
    a = ap.parse_args(argv)
    doc = generate(a.manifest, a.root)
    for rep, e in sorted(doc["entries"].items()):
        print(f"rep {rep}: usable {e.get('usable')} identity {str(e.get('identity'))[:16]} equals binding {e.get('identity_equals_binding')}"
              f"{(' problems ' + str(e.get('problems'))) if e.get('problems') else ''}")
    print(f"wrote {os.path.join(a.root, ORACLE_NAME)} (manifest {doc['manifest_sha256'][:12]}, host {doc['generated']['host']}, "
          f"snapshot problems {doc['generated']['snapshot_problems']})")
    return 0 if all(e.get("usable") for e in doc["entries"].values()) else 1


if __name__ == "__main__":
    sys.exit(main())
