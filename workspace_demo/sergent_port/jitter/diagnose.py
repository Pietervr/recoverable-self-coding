#!/usr/bin/env python3
"""jitter/diagnose.py — S2 diagnostics for the W2 positive bias (24 Oct 2026): B3 beat G3 out of sample on data
generated by the fitted G3 generators (DESIGN_jitter.md rev 6 §7.3 W2), which gate (b) forbids.

    diagnose.py oracle --setting W2 --set 1 [--members 0,3]
        Score every test fold of an archived decision set under the generator's TRUE density on the primary span and
        compare with the archived fitted G3 and B3 fold sums. Three oracle variants per fold, all with the true
        template, amplitudes, s_tau and s_g:
          T    the generator's own mu0[P], Sigma[P,P] + continuous tau (601 nodes, 0.5 ms)   = the Bayes score;
          F    the FOLD's whitening (training-catch mu0, Ledoit-Wolf Sigma) + continuous tau;
          F31  the fold's whitening + the model's 31-node tau grid.
        T - F is the cost of the estimated whitening, F - F31 the cost of the tau grid, F31 - G3_fit the cost of the
        template space and parameter estimation. B3_fit > T is impossible in expectation (the data would not be what
        the oracle thinks they are). Fast (numpy only).
    diagnose.py sigma --setting W2 --set 1 --variant lw|scaled|oracle|em|oracle_em [--workers 6]
        Refit the decision batch of one set (G2/G3+/B2/B3+, the repaired start set, 5 block folds, held-out score)
        under a noise construction, with the per-LEVEL held-out contrast and the fitted s_g / A(k):
          lw         the rev 6 construction: Ledoit-Wolf training-catch Sigma, fixed for both families (no EM);
          scaled     the scaled sample catch covariance (data.whitening 'scaled'), fixed (no EM);
          oracle     the generator's own mu0[P], Sigma[P,P], fixed (mechanism confirmation; unavailable on real data);
          em         the REPAIRED construction: 'scaled' as the start, then Sigma by maximum likelihood within each
                     model (fit.em_fit) and held-out scoring under the model's own Sigma;
          oracle_em  the oracle start followed by the within-model EM (how far EM moves from the truth).
        The first S2 refits of 24 Oct (results W2_set1_sigma_oracle/fold.json) were run under the rev 6 four-start
        recipe by the scratch twin of this command; 'sample' and 'diag' variants exist only in the whitening-loss
        simulation (kl_sigma_simulation.py).
Results: results/s2/diagnosis/<setting>_set<r>_oracle.{json,md}, <setting>_set<r>_sigma_<variant>.json.
"""
