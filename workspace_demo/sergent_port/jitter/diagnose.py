# ----------------------------------------------------------------------------------------------
# the true density of a graded generator on the primary span
# ----------------------------------------------------------------------------------------------
def true_loglik(Y, k, mu0, Sigma, cfg: F.GeneratorConfig, tau_nodes, logw_tau, P=D.PRIMARY_WINDOWS):
    """(n,) log p(y_i) under the graded generator restricted to the windows P, whitening (mu0, Sigma): continuous
    spline template at each tau node, the adaptive 33-node scale rule, log-sum-exp over the tau nodes."""
    gh_x, gh_w = np.polynomial.hermite.hermgauss(N_G_ORACLE)
    L = np.linalg.cholesky(Sigma)
    Linv = np.linalg.inv(L)
    logdet = 2.0 * np.sum(np.log(np.diag(L)))
    U = (Y - mu0) @ Linv.T
    Tt = S.template_windows(cfg, tau_nodes)[:, P]
    V = Tt @ Linv.T
    Pm = U @ V.T
    vv = np.sum(V * V, axis=1)
    uu = np.sum(U * U, axis=1)
    m = cfg.a[k]
    A = m[:, None] * Pm
    B = (m * m)[:, None] * vv[None, :]
    if cfg.s_g > 0:
        node_terms = M._adaptive_log_scale_integral(A, B, cfg.s_g, gh_x, np.log(gh_w), xp=np)
    else:
        node_terms = A - 0.5 * B
    lse = np.logaddexp.reduce(logw_tau[None, :] + node_terms, axis=1)
    return -0.5 * len(P) * M.LOG2PI - 0.5 * logdet - 0.5 * uu + lse


def tau_rule(cfg: F.GeneratorConfig, n: int):
    """(nodes, log weights): the model's 31-node rule, or a fine trapezoid of the continuous truncated normal."""
    if n == 1 or cfg.s_tau_ms <= 0:
        return np.zeros(1), np.zeros(1)
    nodes = np.linspace(-D.TAU_TRUNC_MS, D.TAU_TRUNC_MS, n)
    if n == M.N_TAU_NODES:
        w = M.truncnorm_node_weights(nodes, cfg.s_tau_ms)
    else:
        a = D.TAU_TRUNC_MS / cfg.s_tau_ms
        w = truncnorm.pdf(nodes, -a, a, loc=0.0, scale=cfg.s_tau_ms)
        w[0] *= 0.5
        w[-1] *= 0.5
        w = w / w.sum()
    return nodes, np.log(w)


def run_oracle(setting: str, r: int, members=None) -> dict:
    if s2.SETTINGS[setting][0] != "G3":
        raise ValueError("the oracle density is implemented for graded (G3) generators")
    with open(os.path.join(s2.DEC_DIR, setting, f"set_{r}.json")) as f:
        rec = json.load(f)
    bases = s2.load_bases()
    sp_ = D.span("primary")
    P = D.PRIMARY_WINDOWS
    rows = []
    for part in rec["participants"]:
        m, base = part["m"], part["base"]
        if members is not None and m not in members:
            continue
        cfg = s2.load_config(base, "G3")
        p = s2.make_synthetic(setting, r, m, base, bases)
        if p.data_id != part["data_id"]:
            raise RuntimeError(f"regenerated data identity differs for m{m}")
        nodes_f, logw_f = tau_rule(cfg, N_TAU_FINE)
        nodes_31, logw_31 = tau_rule(cfg, M.N_TAU_NODES)
        mu_t, Sig_t = cfg.mu0[P], cfg.Sigma[np.ix_(P, P)]
        t0 = S.template_windows(cfg, np.zeros(1))[0, P]
        tots = dict(T=0.0, F=0.0, F31=0.0, G3=0.0, B3=0.0)
        folds, shr, nc, vr = [], [], [], []
        for fold in range(5):
            train, test, _, _ = D.fold_datasets(p, sp_, fold)
            T = float(true_loglik(test.Y, test.k, mu_t, Sig_t, cfg, nodes_f, logw_f).sum())
            Fv = float(true_loglik(test.Y, test.k, train.wh.mu0, train.wh.Sigma, cfg, nodes_f, logw_f).sum())
            F31 = float(true_loglik(test.Y, test.k, train.wh.mu0, train.wh.Sigma, cfg, nodes_31, logw_31).sum())
            g3, b3 = part["fold_sums"]["G3"][fold], part["fold_sums"]["B3"][fold]
            for key, v in (("T", T), ("F", Fv), ("F31", F31), ("G3", g3), ("B3", b3)):
                tots[key] += v
            folds.append(dict(T=T, F=Fv, F31=F31, G3=g3, B3=b3, shrinkage=train.wh.shrinkage, n_catch=train.wh.n_catch,
                              var_ratio_template=float(t0 @ Sig_t @ t0) / float(t0 @ train.wh.Sigma @ t0)))
            shr.append(train.wh.shrinkage)
            nc.append(train.wh.n_catch)
            vr.append(folds[-1]["var_ratio_template"])
        n = part["n_scored"]
        d = {k: v / n for k, v in tots.items()}
        rows.append(dict(m=m, base=base, s_tau=cfg.s_tau_ms, s_g=cfg.s_g, strength=cfg.strength, n_scored=n,
                         totals=tots, per_trial=d, T_minus_G3=d["T"] - d["G3"], T_minus_B3=d["T"] - d["B3"],
                         F_minus_G3=d["F"] - d["G3"], F31_minus_G3=d["F31"] - d["G3"], B3_minus_G3=d["B3"] - d["G3"],
                         shrinkage=float(np.mean(shr)), n_catch=float(np.mean(nc)), var_ratio_template=float(np.mean(vr)),
                         folds=folds))
    keys = ("T_minus_G3", "T_minus_B3", "F_minus_G3", "F31_minus_G3", "B3_minus_G3", "shrinkage", "var_ratio_template")
    out = dict(setting=setting, r=r, archived_primary=rec["primary"], n_g_nodes=N_G_ORACLE, n_tau_fine=N_TAU_FINE,
               means={k: float(np.mean([row[k] for row in rows])) for k in keys},
               counts=dict(T_above_B3=int(sum(row["T_minus_B3"] > 0 for row in rows)),
                           F_above_B3=int(sum(row["F_minus_G3"] > row["B3_minus_G3"] for row in rows)),
                           F31_above_B3=int(sum(row["F31_minus_G3"] > row["B3_minus_G3"] for row in rows)),
                           B3_above_G3=int(sum(row["B3_minus_G3"] > 0 for row in rows)), n=len(rows)),
               participants=rows, code_hash=M.code_hash())
    os.makedirs(DIAG_DIR, exist_ok=True)
    stem = os.path.join(DIAG_DIR, f"{setting}_set{r}_oracle")
    with open(stem + ".json", "w") as f:
        json.dump(out, f, indent=1)
    with open(stem + ".md", "w") as f:
        f.write(oracle_markdown(out))
    return out


def oracle_markdown(out: dict) -> str:
    mn, ct = out["means"], out["counts"]
    L = [f"# Oracle test — {out['setting']} set {out['r']} (archived primary {out['archived_primary']})", "",
         "Every test fold scored under the generator's TRUE density on the primary span (continuous template, "
         f"{out['n_tau_fine']}-node tau, {out['n_g_nodes']}-node adaptive scale rule). T = the generator's own mu0/Sigma; "
         "F = the fold's training-catch mu0 and Ledoit-Wolf Sigma; F31 = F with the model's 31-node tau grid. "
         "Differences in nat per scored trial against the archived fitted G3 and B3.", "",
         f"Means over {ct['n']} participants: T − G3 {mn['T_minus_G3']:+.4f}, T − B3 {mn['T_minus_B3']:+.4f}, "
         f"F − G3 {mn['F_minus_G3']:+.4f}, F31 − G3 {mn['F31_minus_G3']:+.4f}, B3 − G3 {mn['B3_minus_G3']:+.4f}; "
         f"mean shrinkage {mn['shrinkage']:.3f}; variance ratio along the zero-shift template t'Σ_gen t / t'Σ̂ t "
         f"{mn['var_ratio_template']:.3f}.", "",
         f"Counts: T above B3 {ct['T_above_B3']}/{ct['n']}; F above B3 {ct['F_above_B3']}; F31 above B3 "
         f"{ct['F31_above_B3']}; B3 above G3 {ct['B3_above_G3']}.", "",
         "| m | base | gen s_tau | s_g | strength | T − G3 | T − B3 | F − G3 | F31 − G3 | B3 − G3 | shrinkage | n_catch | var ratio |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for row in sorted(out["participants"], key=lambda q: -q["B3_minus_G3"]):
        L.append(f"| {row['m']} | S{row['base']} | {row['s_tau']:.1f} | {row['s_g']:.2f} | {row['strength']:.2f} | "
                 f"{row['T_minus_G3']:+.4f} | {row['T_minus_B3']:+.4f} | {row['F_minus_G3']:+.4f} | {row['F31_minus_G3']:+.4f} | "
                 f"{row['B3_minus_G3']:+.4f} | {row['shrinkage']:.3f} | {row['n_catch']:.0f} | {row['var_ratio_template']:.3f} |")
    return "\n".join(L) + "\n"


# ----------------------------------------------------------------------------------------------
# alternative shared-noise constructions
# ----------------------------------------------------------------------------------------------
def make_whitening(variant: str, Ytr, ktr, cfg: F.GeneratorConfig | None, P=D.PRIMARY_WINDOWS) -> D.Whitening:
    """The STARTING whitening of a variant (the EM variants move Sigma from there)."""
    base = variant.replace("_em", "")
    if base in ("lw", "scaled"):
        return D.whitening(Ytr, ktr, base)
    if base == "oracle":
        if cfg is None:
            raise ValueError("oracle needs the generator configuration")
        n = int(np.sum(ktr == 0))
        return D.whitening_from_sigma(cfg.mu0[P], cfg.Sigma[np.ix_(P, P)], 0.0, n)
    raise KeyError(variant)


def sigma_task(setting: str, r: int, m: int, base: int, bases: dict, variant: str) -> dict:
    os.environ.setdefault("NPROC", "1")
    t0 = _time.time()
    model = s2.SETTINGS[setting][0]
    cfg = s2.load_config(base, model) if variant.startswith("oracle") else None
    if variant.startswith("oracle") and setting == "O1":
        cfg = S.with_nuisance(cfg, 0.0, cfg.s_g)
    p = s2.make_synthetic(setting, r, m, base, bases)
    sp_ = D.span("primary")
    Y = p.W53[:, sp_.windows]
    sums = {"G3": [], "B3": []}
    lev = {"G3": np.zeros(6), "B3": np.zeros(6)}
    nlev = np.zeros(6)
    folds = []
    cache = F.FitCache(em=variant.endswith("em"))
    for fold, (tr, te) in enumerate(D.folds(p)):
        wh = make_whitening(variant, Y[tr], p.levels[tr], cfg)
        train = D.make_dataset(Y[tr], p.levels[tr], sp_, wh, f"{p.data_id}/primary/{variant}/fold{fold}/train")
        test = D.make_dataset(Y[te], p.levels[te], sp_, wh, f"{p.data_id}/primary/{variant}/fold{fold}/test")
        res = F.fit_all_models(train, cache, "primary", ("G3", "B3"))
        row = dict(fold=fold, shrinkage=wh.shrinkage, n_catch=wh.n_catch,
                   train={name: res[name].loglik for name in s2.DECISION_SPECS})
        for sel in ("G3", "B3"):
            fr = res[sel]
            row[sel] = dict(selection=fr.selection, loglik=fr.loglik, status=fr.status, flags=fr.flags)
            if fr.available:
                sp = F.selected_spec(sel, fr, "primary")
                Pp = M.unpack(sp, fr.theta)
                row[sel].update(s_tau=Pp.s_tau_ms, s_g=Pp.s_g, a=[float(v) for v in Pp.a[1:]])
                if Pp.A is not None:
                    row[sel].update(A=[float(v) for v in Pp.A[1:]], kappa=Pp.kappa, x0=Pp.x0)
                row[sel].update(em_iterations=fr.em_iterations, em_trace=fr.em_trace)
                ll = F.score_heldout(sp, fr, test)
                sums[sel].append(float(np.sum(ll)))
                for k in range(6):
                    lev[sel][k] += float(np.sum(ll[test.k == k]))
            else:
                sums[sel].append(float("nan"))
        nlev += np.bincount(test.k, minlength=6)
        folds.append(row)
    n = D.n_scored(p)
    scores = {k: (float(np.sum(v) / n) if not np.any(np.isnan(v)) else float("nan")) for k, v in sums.items()}
    return dict(m=m, base=base, variant=variant, n_scored=n, scores=scores, fold_sums=sums,
                delta3=scores["B3"] - scores["G3"],
                delta3_by_level=[float((lev["B3"][k] - lev["G3"][k]) / max(nlev[k], 1)) for k in range(6)],
                n_by_level=nlev.tolist(), folds=folds, seconds=_time.time() - t0)


def run_sigma(setting: str, r: int, variant: str, workers: int) -> dict:
    from joblib import Parallel, delayed
    with open(os.path.join(s2.DEC_DIR, setting, f"set_{r}.json")) as f:
        rec = json.load(f)
    bases = s2.load_bases()
    t0 = _time.time()
    rows = Parallel(n_jobs=workers, backend="loky")(
        delayed(sigma_task)(setting, r, m, s, bases, variant) for m, s in enumerate(rec["members"]))
    d = [row["delta3"] for row in rows if np.isfinite(row["delta3"])]
    iv = X.t_interval(d)
    arch = [rec["delta3"][f"m{row['m']}"] for row in rows]
    nest = [fo["train"]["B3+"] - fo["train"]["G3+"] for row in rows for fo in row["folds"]]
    out = dict(setting=setting, r=r, variant=variant, primary=iv.sign, mean=iv.mean, lo=iv.lo, hi=iv.hi, n_available=len(d),
               n_positive=int(sum(v > 0 for v in d)), archived_primary=rec["primary"], archived_mean=float(np.mean(arch)),
               delta3_by_level_mean=[float(np.mean([row["delta3_by_level"][k] for row in rows])) for k in range(6)],
               nesting_violations=int(sum(v < -1e-6 for v in nest)), worst_nesting_deficit_nat=float(min(nest)),
               participants=rows, wall_s=_time.time() - t0, code_hash=M.code_hash())
    os.makedirs(DIAG_DIR, exist_ok=True)
    with open(os.path.join(DIAG_DIR, f"{setting}_set{r}_sigma_{variant}.json"), "w") as f:
        json.dump(out, f, indent=1)
    print(f"[diagnose sigma {variant}] {setting} set {r}: primary {iv.sign}, Δ₃ mean {iv.mean:+.5f} [{iv.lo:+.5f}, {iv.hi:+.5f}], "
          f"positive {out['n_positive']}/{len(d)} (archived {rec['primary']}, mean {out['archived_mean']:+.5f}); "
          f"by level {np.round(out['delta3_by_level_mean'], 4)}; nesting violations {out['nesting_violations']} "
          f"(worst {out['worst_nesting_deficit_nat']:.1f} nat); {out['wall_s']:.0f} s", flush=True)
    return out


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    o = sub.add_parser("oracle")
    o.add_argument("--setting", default="W2", choices=list(s2.SETTINGS))
    o.add_argument("--set", type=int, default=1)
    o.add_argument("--members", default=None, help="comma-separated member indices (default all)")
    g = sub.add_parser("sigma")
    g.add_argument("--setting", default="W2", choices=list(s2.SETTINGS))
    g.add_argument("--set", type=int, default=1)
    g.add_argument("--variant", required=True, choices=SIGMA_VARIANTS)
    g.add_argument("--workers", type=int, default=6)
    a = ap.parse_args()
    if a.cmd == "oracle":
        members = None if a.members is None else [int(v) for v in a.members.split(",")]
        out = run_oracle(a.setting, a.set, members)
        print(oracle_markdown(out))
    else:
        run_sigma(a.setting, a.set, a.variant, a.workers)


if __name__ == "__main__":
    main()
